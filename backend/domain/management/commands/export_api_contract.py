import json
from pathlib import Path
from django.conf import settings
from django.core.management.base import BaseCommand, CommandError
from domain.contracts import schema_contract


def generated_source():
    return "// Generated by backend/manage.py export_api_contract. Do not edit by hand.\nexport const API_SCHEMA = " + json.dumps(schema_contract(), ensure_ascii=False, indent=2) + " as const;\n"


class Command(BaseCommand):
    help = "Generate/check the public TypeScript field registry (no account or sheet data)"

    def add_arguments(self, parser):
        parser.add_argument("--check", action="store_true")

    def handle(self, *args, **options):
        target = settings.BASE_DIR.parent / "src" / "contracts" / "fieldRegistry.generated.ts"
        source = generated_source()
        if options["check"]:
            if not target.exists() or target.read_text(encoding="utf-8") != source:
                raise CommandError("API field contract is stale; run export_api_contract")
            self.stdout.write("API field contract matches backend schema")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(source, encoding="utf-8", newline="\n")
            self.stdout.write("Generated src/contracts/fieldRegistry.generated.ts")
